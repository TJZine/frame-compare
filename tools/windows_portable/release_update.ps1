function Get-CanonicalManifest([hashtable]$Source, [string]$RequirementsHash) {
  if ($RequirementsHash -cnotmatch '\A[0-9a-f]{64}\z') { throw "Invalid requirements fingerprint." }
  $manifest = @{
    Version = $Source.Version
    RequirementsDigest = $RequirementsHash
    RuntimeFingerprint = $Source.RuntimeFingerprint
    Files = $Source.Files
  }
  return ,(New-UpdateManifestBytes @manifest)
}

function Assert-ReleaseZipEntry([IO.Compression.ZipArchiveEntry]$Entry, [switch]$AllowDirectory) {
  $name = $Entry.FullName
  $isDirectory = $name.EndsWith("/")
  $unixType = ($Entry.ExternalAttributes -shr 16) -band 0xF000
  if (
    !$name -or $name -match '[\\:*?"<>|\x00-\x1f]' -or
    $name -match '(?:^|/)(?:CON|CONIN\$|CONOUT\$|PRN|AUX|NUL|COM[0-9¹²³]|LPT[0-9¹²³])(?:\.[^/]*)?(?:/|$)' -or
    $name -match '[. ](?:/|$)' -or $name.StartsWith("/") -or $name.Contains("//") -or
    ($Entry.ExternalAttributes -band 0x400) -or
    ($isDirectory -and (!$AllowDirectory -or $Entry.Length -ne 0 -or $unixType -notin @(0, 0x4000))) -or
    (!$isDirectory -and (($Entry.ExternalAttributes -band 0x10) -or $unixType -notin @(0, 0x8000)))
  ) {
    throw "Unsafe ZIP entry path or type."
  }
}

function Assert-SourceEntry([IO.Compression.ZipArchiveEntry]$Entry, [object]$File) {
  if ($Entry.Length -ne $File.bytes) { throw "ZIP source size mismatch: $($File.path)" }
  $bytes = Read-ZipEntryBytes $Entry $File.bytes "source payload"
  if ($bytes.Length -ne $File.bytes -or (Get-ReleaseDigest $bytes) -cne $File.sha256) {
    throw "ZIP source digest mismatch: $($File.path)"
  }
}

function Assert-UpdateArchive(
  [string]$Path, [hashtable]$Source, [byte[]]$Manifest, [byte[]]$Signature
) {
  $archiveLength = (Get-Item -LiteralPath $Path).Length
  if ($archiveLength -le 0 -or $archiveLength -gt $MaxUpdateArchiveBytes) {
    throw "Update archive exceeds the archive size limit."
  }
  $zip = [IO.Compression.ZipFile]::OpenRead($Path)
  try {
    Assert-SafeUpdateArchive $zip $archiveLength
    $remaining = [Collections.Generic.Dictionary[string, object]]::new([StringComparer]::Ordinal)
    foreach ($file in $Source.Files) { $remaining.Add("payload/$($file.path)", $file) }
    $manifestEntry = $null
    $signatureEntry = $null
    foreach ($entry in $zip.Entries) {
      Assert-ReleaseZipEntry $entry
      if ($entry.FullName -cnotmatch '\A[A-Za-z0-9._/-]+\z') { throw "Invalid code-only update entry name." }
      switch -CaseSensitive ($entry.FullName) {
        "update-manifest.json" { $manifestEntry = $entry }
        "update-manifest.sig" {
          if (!$Signature) { throw "Unsigned update contains a preexisting signature." }
          $signatureEntry = $entry
        }
        default {
          # The exact trusted file set also rejects implicit directory conflicts
          # and alternate spellings of directories or filenames.
          if (!$remaining.ContainsKey($entry.FullName)) { throw "Unexpected update ZIP entry." }
          Assert-SourceEntry $entry $remaining[$entry.FullName]
          [void]$remaining.Remove($entry.FullName)
        }
      }
    }
    if ($remaining.Count -ne 0 -or $null -eq $manifestEntry -or ($Signature -and $null -eq $signatureEntry)) {
      throw "Update archive is missing required entries."
    }
    $actualManifest = Read-ZipEntryBytes $manifestEntry $MaxManifestBytes "update-manifest.json"
    if ($Signature) {
      $actualSignature = Read-ZipEntryBytes $signatureEntry $MaxSignatureBytes "update-manifest.sig"
      if (
        (Get-ReleaseDigest $actualSignature) -cne (Get-ReleaseDigest $Signature) -or
        !(Verify-ManifestSignature $actualManifest $actualSignature "tools/windows_portable/update_public_key.xml")
      ) { throw "Final update detached signature mismatch." }
    }
    # Equality to independently generated bytes enforces the schema and every
    # value and type, including ordering, encoding and the absence of extras.
    if ((Get-ReleaseDigest $actualManifest) -cne (Get-ReleaseDigest $Manifest)) {
      throw "Update manifest differs from the canonical source, version or compatibility contract."
    }
  } finally { $zip.Dispose() }
}

function Assert-ArchiveRecords(
  [object[]]$Records, [Collections.Generic.Dictionary[string, object]]$Actual, [string]$Label
) {
  $seen = [Collections.Generic.HashSet[string]]::new([StringComparer]::Ordinal)
  foreach ($record in $Records) {
    if (
      $record.path -isnot [string] -or
      ($record.bytes -isnot [long] -and $record.bytes -isnot [int]) -or
      $record.sha256 -isnot [string] -or $record.sha256 -cnotmatch '\A[0-9a-f]{64}\z' -or
      !$seen.Add($record.path) -or !$Actual.ContainsKey($record.path)
    ) { throw "Unexpected or malformed $Label archive member." }
    $member = $Actual[$record.path]
    if ($record.bytes -ne $member.bytes -or $record.sha256 -cne $member.sha256) {
      throw "$Label archive member size or hash mismatch: $($record.path)"
    }
  }
  if ($seen.Count -ne $Actual.Count) { throw "$Label must cover every archive member exactly once." }
}

function Assert-ArchiveDirectories([object[]]$Expected, [string[]]$Actual, [string]$Label) {
  $set = [Collections.Generic.HashSet[string]]::new($Actual, [StringComparer]::Ordinal)
  foreach ($directory in $Expected) {
    if ($directory -isnot [string] -or !$set.Remove($directory)) {
      throw "Unexpected or duplicate $Label archive directory."
    }
  }
  if ($set.Count -ne 0) { throw "$Label must cover every archive directory exactly once." }
}

function Assert-PortableRuntimeInventory([hashtable]$Source, [object]$Info, [object]$Inventory) {
  $scopes = $Source.RuntimeManifest.bundle.runtime_fingerprints
  foreach ($scope in $scopes.PSObject.Properties) {
    if (
      $Info.media_runtime_fingerprints.($scope.Name) -cne $scope.Value -or
      $Inventory.bundle.media_runtime_fingerprints.($scope.Name) -cne $scope.Value
    ) { throw "Portable bundle runtime scope does not match the pinned manifest: $($scope.Name)" }
  }
  $pins = [Collections.Generic.Dictionary[string, object]]::new([StringComparer]::Ordinal)
  foreach ($artifact in $Source.RuntimeManifest.artifacts) { $pins.Add($artifact.id, $artifact) }
  foreach ($artifact in $Inventory.manifest_artifacts) {
    if (!$pins.ContainsKey($artifact.id)) { throw "Unexpected portable runtime artifact in inventory." }
    $pin = $pins[$artifact.id]
    if (
      $artifact.binary_sha256 -cne $pin.sha256 -or $artifact.binary_bytes -ne $pin.bytes -or
      $artifact.binary_url -cne $pin.url -or $artifact.version -cne $pin.version
    ) { throw "Portable runtime artifact inventory does not match the pinned manifest: $($artifact.id)" }
    [void]$pins.Remove($artifact.id)
  }
  if ($pins.Count -ne 0) { throw "Missing pinned portable runtime artifact in inventory." }
}

function Assert-PortableBundle(
  [string]$Path, [hashtable]$Source, [string]$RequirementsHash, [hashtable]$Authority
) {
  $zip = [IO.Compression.ZipFile]::OpenRead($Path)
  try {
    $prefix = "frame-compare-portable-win-x64/"
    if ($zip.Entries.Count -gt 100000) { throw "Portable bundle exceeds the entry count limit." }
    $entries = [Collections.Generic.Dictionary[string, IO.Compression.ZipArchiveEntry]]::new(
      [StringComparer]::OrdinalIgnoreCase
    )
    $directories = [Collections.Generic.Dictionary[string, string]]::new([StringComparer]::OrdinalIgnoreCase)
    $totalBytes = [long]0
    foreach ($entry in $zip.Entries) {
      if (!$entry.FullName.StartsWith($prefix, [StringComparison]::Ordinal)) {
        throw "Portable bundle entry outside its canonical root."
      }
      Assert-ReleaseZipEntry $entry -AllowDirectory
      if ($entry.Length -lt 0 -or $entry.Length -gt 512MB -or $totalBytes -gt (8GB - $entry.Length)) {
        throw "Portable archive exceeds its expanded size limit."
      }
      $totalBytes += $entry.Length
      if (!$entries.TryAdd($entry.FullName, $entry)) { throw "Duplicate or case-colliding portable ZIP entry." }
      $name = $entry.FullName
      $end = $name.LastIndexOf("/")
      while ($end -ge 0) {
        $directory = $name.Substring(0, $end)
        if (!$directories.TryAdd($directory, $directory) -and $directories[$directory] -cne $directory) {
          throw "Case-colliding portable ZIP directories."
        }
        $end = $directory.LastIndexOf("/")
      }
    }
    foreach ($directory in $directories.Keys) {
      if ($entries.ContainsKey($directory)) { throw "Conflicting portable ZIP file and directory." }
    }
    foreach ($leaf in @("bundle_info.json", "bundle_inventory.json", "manifest.json", "requirements.lock.txt")) {
      if (!$entries.ContainsKey("$prefix$leaf") -or $entries["$prefix$leaf"].FullName -cne "$prefix$leaf") {
        throw "Missing canonical portable bundle entry: $leaf"
      }
    }
    $bundleInfo = [Text.Encoding]::UTF8.GetString(
      (Read-ZipEntryBytes $entries["$($prefix)bundle_info.json"] 64KB "bundle_info.json")
    ) | ConvertFrom-Json -Depth 8
    $inventoryText = [Text.UTF8Encoding]::new($false, $true).GetString(
      (Read-ZipEntryBytes $entries["$($prefix)bundle_inventory.json"] 32MB "bundle_inventory.json")
    )
    $inventory = $inventoryText | ConvertFrom-Json -Depth 12
    $requirements = Read-ZipEntryBytes $entries["$($prefix)requirements.lock.txt"] 4MB "requirements.lock.txt"
    if (
      $bundleInfo.schema_version -ne 3 -or $bundleInfo.bundle_kind -cne "full" -or
      $bundleInfo.platform -cne "windows-x64" -or $bundleInfo.app_version -cne $Source.Version -or
      $inventory.schema_version -ne 2 -or $inventory.bundle.commit_sha -cne $ExpectedSha -or
      $inventory.bundle.source_archive_url -cne "https://github.com/TJZine/frame-compare/archive/$ExpectedSha.tar.gz" -or
      $inventory.bundle.version -cne $Source.Version -or
      $bundleInfo.requirements_lock_sha256 -cne $RequirementsHash -or
      $inventory.bundle.requirements_lock_sha256 -cne $RequirementsHash -or
      (Get-ReleaseDigest $requirements) -cne $RequirementsHash -or
      $bundleInfo.media_runtime_fingerprint -cne $Source.RuntimeFingerprint -or
      $inventory.bundle.media_runtime_fingerprint -cne $Source.RuntimeFingerprint
    ) { throw "Portable bundle source, version or compatibility fingerprints mismatch." }

    $actual = [Collections.Generic.Dictionary[string, object]]::new([StringComparer]::Ordinal)
    foreach ($entry in $zip.Entries) {
      if ($entry.FullName.EndsWith("/") -or $entry.FullName -ceq "$($prefix)bundle_inventory.json") { continue }
      $name = $entry.FullName.Substring($prefix.Length)
      $actual.Add($name, (Get-ArchiveEntryRecord $entry))
    }
    $actualDirectories = [string[]]@($directories.Values | Where-Object { $_ -cne $prefix.TrimEnd("/") } |
      ForEach-Object { $_.Substring($prefix.Length) })
    if ($inventory.archive.files -isnot [array] -or $inventory.archive.directories -isnot [array]) {
      throw "Malformed portable archive inventory."
    }
    Assert-ArchiveRecords $inventory.archive.files $actual "Producer inventory"
    Assert-ArchiveDirectories $inventory.archive.directories $actualDirectories "Producer inventory"

    foreach ($file in $Authority.SourceFiles.GetEnumerator()) {
      if (
        !$actual.ContainsKey($file.Key) -or
        $actual[$file.Key].bytes -ne $file.Value.bytes -or
        $actual[$file.Key].sha256 -cne $file.Value.sha256
      ) { throw "Portable member does not match approved source: $($file.Key)" }
      [void]$actual.Remove($file.Key)
    }
    Assert-PortableRuntimeInventory $Source $bundleInfo $inventory
    if (@($actual.Keys | Where-Object { $_ -match '^(?:app/src/frame_compare|shim)/' }).Count -ne 0) {
      throw "Portable archive has unexpected source or shim members."
    }
  } finally { $zip.Dispose() }
}

function Write-CanonicalUpdateArchive(
  [string]$UnsignedPath, [string]$Target, [hashtable]$Source, [byte[]]$Manifest, [byte[]]$Signature
) {
  # Re-emit only the verified entry set. In particular, leave the input ZIP's
  # headers, attributes and any data outside its central directory behind.
  $inputZip = [IO.Compression.ZipFile]::OpenRead($UnsignedPath)
  try {
    $outputZip = [IO.Compression.ZipFile]::Open($Target, [IO.Compression.ZipArchiveMode]::Create)
    try {
      foreach ($file in $Source.Files) {
        $name = "payload/$($file.path)"
        $payloadBytes = Read-ZipEntryBytes ($inputZip.GetEntry($name)) $file.bytes "source payload"
        Add-CanonicalUpdateEntry $outputZip $name $payloadBytes
      }
      Add-CanonicalUpdateEntry $outputZip "update-manifest.json" $Manifest
      if ($Signature) { Add-CanonicalUpdateEntry $outputZip "update-manifest.sig" $Signature }
    } finally { $outputZip.Dispose() }
  } finally { $inputZip.Dispose() }
}

function Add-CanonicalUpdateEntry([IO.Compression.ZipArchive]$Zip, [string]$Name, [byte[]]$Bytes) {
  $entry = $Zip.CreateEntry($Name, [IO.Compression.CompressionLevel]::Optimal)
  $entry.LastWriteTime = [DateTimeOffset]::new(1980, 1, 1, 0, 0, 0, [TimeSpan]::Zero)
  $stream = $entry.Open()
  try { $stream.Write($Bytes, 0, $Bytes.Length) } finally { $stream.Dispose() }
}

$source = Get-ReleaseSourceContract $ExpectedSha $ReleaseTag
New-Item -ItemType Directory -Path $OutputDir | Out-Null
$bundlePath = Join-Path $InputDir "portable.zip"
$updatePath = Join-Path $InputDir "unsigned-update.zip"
$manifestPath = Join-Path $InputDir "manifest.json"
$receiptPath = Join-Path $InputDir "verification.json"

if ($Stage -eq "Verify") {
  Assert-ReleaseFileDigest $bundlePath $BundleDigest 2GB
  Assert-ReleaseFileDigest $updatePath $UpdateDigest $MaxUpdateArchiveBytes
  $canonical = Get-CanonicalManifest $source $RequirementsDigest
  Assert-UpdateArchive $updatePath $source $canonical
  $catalogDigest = $null
  if ($RequirePortableAuthority) {
    Assert-ReleaseFileDigest $RequirementsPath $RequirementsDigest 4MB
    $verifiedBundle = Join-Path $OutputDir "verified-portable.zip"
    $verifiedUpdate = Join-Path $OutputDir "verified-update.zip"
    $catalogDigest = Write-IndependentPortableZip $bundlePath $verifiedBundle $RequirementsPath
    Write-CanonicalUpdateArchive $updatePath $verifiedUpdate $source $canonical
    Assert-UpdateArchive $verifiedUpdate $source $canonical
    $BundleDigest = Get-ReleaseFileDigest $verifiedBundle
    $UpdateDigest = Get-ReleaseFileDigest $verifiedUpdate
  } else {
    Assert-PortableBundle $bundlePath $source $RequirementsDigest (Get-PortableAuthority $ExpectedSha $source)
  }
  [IO.File]::WriteAllBytes((Join-Path $OutputDir "manifest.json"), $canonical)
  [ordered]@{
    schema = 2
    commit = $ExpectedSha
    tag = $ReleaseTag
    bundle_sha256 = $BundleDigest
    unsigned_update_sha256 = $UpdateDigest
    requirements_sha256 = $RequirementsDigest
    portable_catalog_sha256 = $catalogDigest
    manifest_sha256 = Get-ReleaseDigest $canonical
  } | ConvertTo-Json -Compress | Set-Content -LiteralPath (Join-Path $OutputDir "verification.json") -Encoding utf8NoBOM
  return
}

Assert-ReleaseFileDigest $receiptPath $VerificationDigest 4KB
Assert-ReleaseFileDigest $manifestPath $ManifestDigest 4MB
$receipt = Get-Content -LiteralPath $receiptPath -Raw | ConvertFrom-Json -Depth 4
if (
  $receipt.schema -ne 2 -or $receipt.commit -cne $ExpectedSha -or $receipt.tag -cne $ReleaseTag -or
  $receipt.manifest_sha256 -cne $ManifestDigest -or
  $receipt.bundle_sha256 -cnotmatch '\A[0-9a-f]{64}\z' -or
  $receipt.unsigned_update_sha256 -cnotmatch '\A[0-9a-f]{64}\z' -or
  $receipt.portable_artifact_id -cnotmatch '\A[1-9][0-9]*\z' -or
  $receipt.unsigned_update_artifact_id -cnotmatch '\A[1-9][0-9]*\z' -or
  $receipt.portable_artifact_id -ceq $receipt.unsigned_update_artifact_id
) { throw "Verification receipt does not bind this release and manifest." }
$canonical = Get-CanonicalManifest $source $receipt.requirements_sha256
if ((Get-ReleaseDigest $canonical) -cne $ManifestDigest) { throw "Signing input differs from the approved source." }

if ((git ls-tree --name-only $ExpectedSha -- $portableCatalogPath) -cne $portableCatalogPath) {
  throw "Release requires the approved portable runtime catalog."
}
Assert-ReleaseFileDigest $portableCatalogPath $receipt.portable_catalog_sha256 32MB
if ($Stage -eq "PrepareSigning") {
  [IO.File]::WriteAllBytes((Join-Path $OutputDir "manifest.json"), $canonical)
  return
}

if (
  $receipt.portable_artifact_id -cne $VerifiedBundleId -or
  $receipt.unsigned_update_artifact_id -cne $VerifiedUpdateId
) { throw "Release input artifact IDs do not match the verification receipt." }
$bundlePath = Join-Path $InputDir "verified-portable.zip"
$updatePath = Join-Path $InputDir "verified-update.zip"
$signaturePath = Join-Path $InputDir "detached-signature.json"
Assert-ReleaseFileDigest $signaturePath $SignatureDigest $MaxSignatureBytes
$signed = Get-Content -LiteralPath $signaturePath -Raw | ConvertFrom-Json -Depth 4
if ($signed.verification_sha256 -cne $VerificationDigest -or $signed.manifest_sha256 -cne $ManifestDigest) {
  throw "Detached signature receipt does not bind the verified inputs."
}
$signatureBytes = [Text.Encoding]::ASCII.GetBytes($signed.signature)
if (!(Verify-ManifestSignature $canonical $signatureBytes "tools/windows_portable/update_public_key.xml")) {
  throw "Detached signature does not verify against the approved manifest."
}
Assert-ReleaseFileDigest $bundlePath $receipt.bundle_sha256 2GB
Assert-ReleaseFileDigest $updatePath $receipt.unsigned_update_sha256 $MaxUpdateArchiveBytes
Assert-UpdateArchive $updatePath $source $canonical
$updateVersion = if ($ReleaseTag) { $ReleaseTag } else { $source.Version }
$portableName = if ($ReleaseTag) { "frame-compare-portable-win-x64-$ReleaseTag.zip" } else { "frame-compare-portable-win-x64.zip" }
$portableTarget = Join-Path $OutputDir $portableName
$updateTarget = Join-Path $OutputDir "frame-compare-update-win-x64-$updateVersion.zip"
Copy-Item -LiteralPath $bundlePath -Destination $portableTarget
Write-CanonicalUpdateArchive $updatePath $updateTarget $source $canonical $signatureBytes
Assert-UpdateArchive $updateTarget $source $canonical $signatureBytes
foreach ($asset in @($portableTarget, $updateTarget)) {
  $name = Split-Path -Leaf $asset
  "$(Get-ReleaseFileDigest $asset)  $name" | Set-Content -LiteralPath "$asset.sha256" -Encoding ASCII
}
